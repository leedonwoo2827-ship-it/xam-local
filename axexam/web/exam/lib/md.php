<?php
/**
 * 답변 서식 — 아주 좁은 마크다운만.
 *
 * ── 왜 필요한가 ────────────────────────────────────────────────────────────
 * LLM 초안이 `**데이터 분석의 전체 흐름**` 처럼 마크다운을 쓴다. 그대로 두면 화면에
 * 별표가 그냥 보인다 — 강조가 아니라 noise 다.
 *
 * ── 왜 라이브러리를 안 쓰는가 ──────────────────────────────────────────────
 * 답변은 LLM 이 쓴 텍스트다. 범용 마크다운 변환기는 원시 HTML 통과를 허용하는 것이
 * 기본값인 경우가 많고, 그러면 `<script>` 가 그대로 나간다. 관리자가 검수한다지만
 * 눈으로 스크립트를 잡으라고 할 수는 없다.
 *
 * → **이스케이프를 먼저 하고, 그다음 우리가 아는 태그만 되돌린다.**
 *   이 순서면 LLM 이 쓴 어떤 HTML 도 살아남지 못한다. 지원 문법을 좁게 두는 것이
 *   기능 축소가 아니라 안전 장치다.
 *
 * ── 함수 두 개인 이유 ──────────────────────────────────────────────────────
 *   ex_md_html()   우리가 그리는 화면(관리자 초안 박스 등) — 진짜 <b> 로 렌더
 *   ex_md_plain()  그누보드 게시판 댓글 — **평문**으로 정리
 *
 * 게시판 댓글을 HTML 로 쓰지 않는 이유: 댓글의 HTML 허용 여부는 그누보드 코어가
 * `wr_option` 을 보고 정하는데, 그 코어는 우리 저장소에 없다(스킨만 있다).
 * 추측으로 `html1` 을 켜면 (a) 안 켜져서 태그가 글자로 보이거나
 * (b) 켜져서 우리 의도보다 넓게 HTML 이 허용된다. 둘 다 나쁘다.
 * 평문으로 정리하면 어느 쪽이든 읽을 수 있게 나온다.
 */
if (!defined('_GNUBOARD_')) exit;

/**
 * 지원하는 문법 — 이것만이다.
 *
 *   **굵게**        → <b>굵게</b>
 *   `코드`          → <code>코드</code>
 *   - 항목 / * 항목 → 불릿 목록
 *   빈 줄           → 문단
 *   줄바꿈          → <br>
 *
 * 표·제목(#)·링크·이미지는 **지원하지 않는다.** 프롬프트에서 쓰지 말라고 못 박아
 * 두었다(prompt.php 규칙 8) — 렌더러가 모르는 문법을 쓰면 기호가 그대로 보인다.
 */
function ex_md_html($text)
{
    // ① 먼저 전부 이스케이프한다. 이 뒤에 남는 <, > 는 우리가 넣은 것뿐이다.
    $s = htmlspecialchars((string)$text, ENT_QUOTES, 'UTF-8');
    $s = str_replace(array("\r\n", "\r"), "\n", $s);

    // ② 인라인 — 코드를 먼저 처리한다. 코드 안의 별표를 강조로 먹지 않게.
    $s = preg_replace('/`([^`\n]+)`/u', '<code>$1</code>', $s);
    //   **굵게** — 최소 매칭. 줄을 넘지 않는다(문단 전체가 굵어지는 사고를 막는다).
    $s = preg_replace('/\*\*([^*\n]+)\*\*/u', '<b>$1</b>', $s);

    // ③ 블록 — 빈 줄로 자르고, 불릿만 있는 덩어리는 <ul> 로 만든다.
    $out = array();
    foreach (preg_split('/\n{2,}/u', $s) as $blk) {
        $blk = trim($blk);
        if ($blk === '') continue;

        $lines  = explode("\n", $blk);
        $bul    = array();
        $is_all = true;
        foreach ($lines as $ln) {
            if (preg_match('/^\s*[-*]\s+(.+)$/u', $ln, $m)) $bul[] = $m[1];
            else { $is_all = false; break; }
        }
        if ($is_all && $bul) {
            $li = '';
            foreach ($bul as $b) $li .= '<li>' . $b . '</li>';
            $out[] = '<ul>' . $li . '</ul>';
        } else {
            $out[] = '<p>' . implode('<br>', $lines) . '</p>';
        }
    }
    return implode("\n", $out);
}

/**
 * 마크다운 기호를 떼어 **평문**으로 만든다. 게시판 댓글용.
 *
 * 지우는 것이 아니라 **읽히게** 바꾼다:
 *   **굵게**  → 굵게        (강조는 사라지지만 문장은 그대로다)
 *   `코드`    → 코드
 *   - 항목    → · 항목      (평문에서 불릿으로 읽힌다)
 */
function ex_md_plain($text)
{
    $s = str_replace(array("\r\n", "\r"), "\n", (string)$text);
    $s = preg_replace('/`([^`\n]+)`/u', '$1', $s);
    $s = preg_replace('/\*\*([^*\n]+)\*\*/u', '$1', $s);
    $s = preg_replace('/^\s*[-*]\s+/mu', '· ', $s);
    return trim($s);
}
