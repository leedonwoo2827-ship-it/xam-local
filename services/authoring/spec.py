# ── 파트 프롬프트 ──────────────────────────────────────────────────────────
# ── 집필 기준 ───────────────────────────────────────────────────────────────
# 두 가지다. 화면에서 고르고 **기본은 `exam`(시험기준)** 이다(2026-08-10 지시).
#
#   exam   : **기본.** 기출을 보지 않고 실제 시험 기준으로 새로 설계한다.
#            `derived_from` 은 빈 문자열.
#   derive : 기출의 **주제·개념만 유지**하고 문장·수치·맥락을 전면 교체한다.
#            ★ 목적이 "파생" 이 아니라 **저작권 회피**다. 같은 주제를 다루되 기출의
#              표현을 재사용하지 않는 것이 요구다.
#            `derived_from` 에 기출 id 를 적어 추적을 남긴다.
#
# ★ 처음에 `derive` 를 "기출에서 파생한다" 로만 썼다 — 틀렸다. 그렇게 쓰면 모델이
#   기출 문장을 손질하는 쪽으로 가고, 그것이 정확히 피하려는 것이다. 그리고 원 집필
#   프롬프트가 적어 둔 함정에도 걸린다: *"기출의 자체 분포는 실제 시험보다 쉽다.
#   표면만 재작성하면 쉬운 문제집이 복제된다."*
#   두 모드 모두 **난이도는 실전 기준**이고, 기출은 난이도의 기준이 아니다.
# 화면 라벨 — 사용자가 정한 문구다(2026-08-10). 순서가 곧 콤보 순서이고 **앞이 기본값**.
MODES = ("exam", "derive")
MODE_LABEL = {"exam": "시험기준으로", "derive": "연습문제화"}


def part_prompt(*, round_code: str, numbers: List[int], subject_nos: List[int],
                difficulty_ask: str, derive_hint: str = "",
                mode: str = "derive",
                round_index: int = 0, round_total: int = 0) -> str:
    """이 파트에서 무엇을 쓸지. **회차마다 달라지는 것만** 여기 담는다.

    ★ 시스템 프롬프트(SYSTEM)와 섞지 않는다 — 그쪽은 캐시 접두라 고정이어야 한다.

    `derive_hint` 는 기출 파일명 목록이다. 파일 내용을 넣지 않고 **이름만** 준다:
    모델이 Read 로 필요한 것만 읽는 편이, 240문항을 프롬프트에 붓는 것보다 싸다
    (실측: 문항 1개에 `Read:01/01-01.md` 1회로 끝났다).
    `mode="exam"` 이면 이 목록을 주지 않는다.
    """
    subj_lines = "\n".join(
        f"    {n}과목 {SUBJECTS[n]} — 문항번호 {(n-1)*20+1}~{n*20}"
        for n in sorted(set(subject_nos)))
    rng = f"{numbers[0]}~{numbers[-1]}" if len(numbers) > 1 else str(numbers[0])

    if mode == "exam" or not derive_hint:
        basis = ("\n■ 집필 기준 — **실제 시험 기준.**\n"
                 "  출제 범위의 개념을 실전 난이도로 **새로 설계한다.** 기출을 읽을 필요가\n"
                 "  없고, 읽더라도 그 난이도에 맞추지 않는다.\n"
                 "  derived_from 은 **빈 문자열**로 둔다.\n")
    else:
        # ★ 목적이 저작권 회피다. "파생" 이라고만 쓰면 모델이 기출 문장을 손질하는
        #   쪽으로 가는데, 그것이 정확히 피하려는 것이다. 무엇을 바꿔야 하는지 나열한다.
        basis = (f"\n■ 집필 기준 — **기출의 주제만 유지한다. 목적은 저작권 회피다.**\n"
                 f"  작업 폴더의 `01/` 에 기출 MD 가 있다. 아래 중에서 골라 "
                 f"**Read 로 읽고**, 그 문항이 **무엇을 묻는지(주제·개념)만** 가져온다.\n"
                 f"  {derive_hint}\n"
                 f"  ★ 다음을 **전부 바꾼다.** 하나라도 남으면 저작권 회피가 성립하지 않는다:\n"
                 f"    · 문장 — 발문·보기·해설의 표현을 재사용하지 않는다. 어순만 바꾸는 것도 안 된다.\n"
                 f"    · 수치 — 표·계산의 숫자를 전부 새로 잡고 정답을 다시 검산한다.\n"
                 f"    · 맥락 — 사례·회사·상황 설정을 다른 것으로 바꾼다.\n"
                 f"    · 보기 구성 — 오답을 그대로 옮기지 않고 혼동 지점을 새로 고른다.\n"
                 f"  ★ 난이도는 **기출을 따르지 않는다.** 기출은 실제 시험보다 쉽다 —\n"
                 f"    주제만 가져오고 난이도는 위의 실전 기준으로 올린다.\n"
                 f"  derived_from 에는 주제를 가져온 기출의 id(파일명에서 `.md` 를 뗀 것)를 쓴다.\n")

    # ★ 회차 차별화. 회차마다 **따로** 호출되므로 서로를 볼 수 없다 — 아무 말도 안 하면
    #   같은 하위개념이 회차마다 반복된다. 원 프롬프트도 같은 것을 요구했다:
    #   *"9회차를 서로 다른 하위주제로 차별화하고."*
    diff = ""
    if round_total > 1 and round_index:
        diff = (f"\n■ 회차 차별화 — 이것은 {round_total}회차 중 **{round_index}회차**다.\n"
                f"  다른 회차와 **같은 하위개념을 반복하지 않는다.** 같은 대주제라도\n"
                f"  다른 각도(정의 ↔ 계산 ↔ 사례 판단)와 다른 세부 항목으로 낸다.\n"
                + ("  뒤 회차이므로 '상' 난이도를 구간 상단에 맞춘다.\n"
                   if round_index > round_total / 2 else ""))

    return f"""\
회차 {round_code} 의 문항 {rng} ({len(numbers)}문항)을 집필한다.

■ 과목 배정 — 문항번호로 정해진다. 바꾸지 않는다.
{subj_lines}

■ 이 파트의 난이도
  {difficulty_ask}
{basis}{diff}
■ 지킬 것
  · question_no 는 {rng} 안의 값만 쓰고, {len(numbers)}개를 **빠짐없이** 쓴다.
  · 정답 위치(answer_index)를 한쪽에 몰지 않는다.
  · 계산형은 계산을 끝까지 해서 정답을 확정한 뒤 보기를 만든다.
    보기 4개 중 오답 3개는 **틀리는 방식이 서로 달라야** 한다
    (예: 복제 계수를 빼먹은 값 / 압축을 평균으로 계산한 값 / 단위를 틀린 값).
"""


def difficulty_plan(n_parts: int) -> List[str]:
    """파트(= 과목 1개, 20문항)별 난이도 요청문.

    회차 목표(프롬프트 문서): 합 80 = 상 28~32 · 중 42~46 · 하 6~8.
    4과목으로 나누면 과목당 **상 7~8 · 중 11 · 하 1~2** 다.

    ★ 과목마다 같은 문장을 주면 네 과목이 서로 비슷해진다. 과목 성격에 맞춰 가른다 —
      1과목(기획)은 개념·절차라 '하' 를 여기에 몰고, 2·3과목(탐색·모델링)은 계산이
      많아 '상' 을 올린다. 4과목(결과 해석)은 지표 해석이라 조합형이 잘 붙는다.
      실측 m01 의 분포(하 7 · 중 45 · 상 28)와 같은 자리에 떨어진다.
    """
    asks = [
        # 1과목 · 빅데이터 분석 기획
        "상 7문항 · 중 11문항 · 하 2문항. 계산형 3문항 이상. "
        "KDD·CRISP-DM·SEMMA 단계 순서와 가명·익명·총계처리 구분을 반드시 다룬다.",
        # 2과목 · 빅데이터 탐색
        "상 8문항 · 중 11문항 · 하 1문항. 계산형 5문항 이상 "
        "(IQR 이상값 경계 · 상관계수 · 표본오차 · 정규화/표준화 환산).",
        # 3과목 · 빅데이터 모델링
        "상 8문항 · 중 11문항 · 하 1문항. 계산형 5문항 이상 "
        "(엔트로피·지니·정보이득 · 오즈비 · 거리 계산). "
        "ㄱ/ㄴ/ㄷ/ㄹ 조합형을 2문항 이상 넣는다.",
        # 4과목 · 빅데이터 결과 해석
        "상 7문항 · 중 11문항 · 하 2문항. 계산형 5문항 이상 "
        "(혼동행렬→정밀도·재현율·F1 · R²·수정R² · RMSE/MAE 비교 · AUC 해석). "
        "ㄱ/ㄴ/ㄷ/ㄹ 조합형을 2문항 이상 넣는다.",
    ]
    if n_parts <= len(asks):
        return asks[:n_parts]
    # 과목 수보다 파트가 많으면(작은 part_size) 돌려 쓴다 — 권장 구성은 아니다
    return [asks[i % len(asks)] for i in range(n_parts)]
